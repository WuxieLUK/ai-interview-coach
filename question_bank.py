def _rotate(items, offset):
    items = list(items)
    if not items:
        return []
    offset = offset % len(items)
    return items[offset:] + items[:offset]


def _first(items, predicate):
    for item in items:
        if predicate(item):
            return item
    return None


def all_questions():
    for family, items in QUESTIONS.items():
        for q in items:
            yield q


def get_question(qid):
    for q in all_questions():
        if q["id"] == qid:
            return q
    return None


def family_questions(family_key):
    if family_key in QUESTIONS:
        return QUESTIONS[family_key]
    return QUESTIONS["general"]


def build_session_questions(family_key, count=5, level="校招", offset=0):
    """按“破冰 → 岗位基础 → 通用行为 → 岗位进阶 → 综合情景”的节奏组卷。

    offset 用于轮换题目，避免每次练习都抽到完全相同的 5 题。
    """
    fam = _rotate(family_questions(family_key), offset)
    gen = _rotate(QUESTIONS["general"], offset)

    picked = []

    # 1) 破冰：岗位向自我介绍 / 难度 1 的行为题
    q = _first(fam, lambda x: x.get("type") == "behavioral" and x.get("difficulty", 1) <= 1) or fam[0]
    picked.append(q)

    def used(qid):
        return qid in [p["id"] for p in picked]

    # 2) 岗位基础：优先难度 1，其次难度 2 的专业题
    q = _first(fam, lambda x: not used(x["id"]) and x.get("type") != "behavioral" and x.get("difficulty", 1) == 1)
    if q is None:
        q = _first(fam, lambda x: not used(x["id"]) and x.get("type") != "behavioral" and x.get("difficulty", 1) <= 2)
    if q:
        picked.append(q)

    # 3) 通用行为：难度 2 的行为故事
    q = _first(gen, lambda x: x.get("type") == "behavioral" and x.get("difficulty", 1) >= 2)
    if q:
        picked.append(q)

    # 4) 岗位进阶：优先难度 3，其次难度 2 的专业/情景题
    q = _first(fam, lambda x: not used(x["id"]) and x.get("type") != "behavioral" and x.get("difficulty", 1) == 3)
    if q is None:
        q = _first(fam, lambda x: not used(x["id"]) and x.get("type") != "behavioral" and x.get("difficulty", 1) >= 2)
    if q:
        picked.append(q)

    # 5) 综合情景 / 收尾
    q = _first(fam, lambda x: not used(x["id"]) and x.get("type") == "situational")
    if q is None:
        q = _first(gen, lambda x: x.get("type") == "situational")
    if q:
        picked.append(q)

    # 补齐其余题位：交替从岗位库与通用库取未用过的题
    while len(picked) < count:
        nxt = _first(fam, lambda x: not used(x["id"])) or _first(gen, lambda x: not used(x["id"]))
        if nxt is None:
            break
        picked.append(nxt)

    return [q["id"] for q in picked[:count]]